const municipalityOptionsCache = new Map<string, SiigoMexicoLocationOption[]>()
const stateCodes = new Set(SIIGO_MEXICO_STATES.map(state => state.value))

export function isSiigoMexicoStateCode(value: string): boolean {
  return stateCodes.has(value)
}

export function getSiigoMexicoMunicipalities(stateCode: string): SiigoMexicoLocationOption[] {
  const cachedOptions = municipalityOptionsCache.get(stateCode)
  if (cachedOptions) return cachedOptions

  const options = (SIIGO_MEXICO_MUNICIPALITY_ENTRIES[stateCode] ?? [])
    .map(([label, value]) => ({ label, value }))
  municipalityOptionsCache.set(stateCode, options)
  return options
}

export function isSiigoMexicoMunicipalityCode(stateCode: string, cityCode: string): boolean {
  return (SIIGO_MEXICO_MUNICIPALITY_ENTRIES[stateCode] ?? [])
    .some(([, value]) => value === cityCode)
}
